CREATE TABLE IF NOT EXISTS chatbot_faqs (
    id          BIGSERIAL PRIMARY KEY,
    question    VARCHAR(250) NOT NULL,
    answer      TEXT NOT NULL,
    keywords    VARCHAR(500) NOT NULL DEFAULT '',
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_by  UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_chatbot_faq_question CHECK (length(trim(question)) >= 3),
    CONSTRAINT chk_chatbot_faq_answer CHECK (length(trim(answer)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_chatbot_faq_question
    ON chatbot_faqs (lower(question));
CREATE INDEX IF NOT EXISTS idx_chatbot_faq_active_order
    ON chatbot_faqs (is_active, sort_order);

